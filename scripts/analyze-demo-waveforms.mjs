// Regenerates constants/demoWaveforms.js: real waveform levels for the demo
// tracks, analysed with the same code the app runs on imported tracks.
// Needs ffmpeg. Run: node scripts/analyze-demo-waveforms.mjs
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const RATE = 22050;
const FILES = {
  'demo-edm-detection-mode': 'edm-detection-mode.mp3',
  'demo-blippy-trance': 'blippy-trance.mp3',
  'demo-neon-laser-horizon': 'neon-laser-horizon.mp3',
};

// The app's modules are plain ES modules without a package "type", so load
// copies of them as .mjs.
const tmp = mkdtempSync(join(tmpdir(), 'cdj-wave-'));
const load = async (rel) => {
  const out = join(tmp, rel.replace(/\//g, '_') + '.mjs');
  writeFileSync(out, readFileSync(join(root, rel), 'utf8'));
  return import(pathToFileURL(out).href);
};
const { computePeaks, computeBands } = await load('utils/audioAnalysis.js');
const { packPeaks, packBands } = await load('utils/peakPacking.js');

const entries = {};
for (const [id, file] of Object.entries(FILES)) {
  const raw = execFileSync(
    'ffmpeg',
    ['-v', 'error', '-i', join(root, 'assets/audio', file), '-ac', '1', '-ar', String(RATE), '-f', 'f32le', '-'],
    { maxBuffer: 1 << 30 }
  );
  const mono = new Float32Array(raw.buffer, raw.byteOffset, raw.byteLength / 4);
  entries[id] = { peaks: packPeaks(computePeaks(mono)), bands: packBands(computeBands(mono, RATE)) };
  console.log(id, (mono.length / RATE).toFixed(1), 's');
}

writeFileSync(
  join(root, 'constants/demoWaveforms.js'),
  `// Generated by scripts/analyze-demo-waveforms.mjs — do not edit by hand.\n` +
    `// Packed waveform levels for the demo tracks (see utils/peakPacking.js).\n` +
    `export const DEMO_WAVEFORMS = ${JSON.stringify(entries, null, 2)};\n`
);
